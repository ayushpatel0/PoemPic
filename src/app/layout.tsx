
import type { Metadata } from 'next';
import { Inter, Noto_Sans_Devanagari } from 'next/font/google'; // Import Noto Sans Devanagari
import './globals.css';
import { Toaster } from "@/components/ui/toaster";

// Initialize fonts with subsets
const inter = Inter({ subsets: ['latin'], variable: '--font-inter' });
const notoSansDevanagari = Noto_Sans_Devanagari({
  subsets: ['devanagari'],
  variable: '--font-noto-sans-devanagari', // CSS variable for this font
  display: 'swap', // Improve font loading performance
});


export const metadata: Metadata = {
  title: 'PoemPic - AI Shayari Generator from Photos',
  description: 'Upload an image and get a unique Hindi shayari generated by AI based on its content and mood.',
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      {/* Apply multiple font variables */}
      <body className={`${inter.variable} ${notoSansDevanagari.variable} font-sans antialiased`} suppressHydrationWarning={true}>
        {children}
        <Toaster />
      </body>
    </html>
  );
}
